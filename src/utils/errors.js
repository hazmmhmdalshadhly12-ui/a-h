/**
 * أداة أخطاء آمنة — تمنع تسريب أي معلومات داخلية من قاعدة البيانات للواجهة.
 *
 * مشكلة فحص الأمان: لما طلب (مثل جلب أسئلة الامتحان أو تسليمه) يفشل،
 * كان `error.message` الخام من PostgREST بيظهر للمستخدم، وفيه معلومات
 * عن قاعدة البيانات نفسها (أسماء الجداول/الدوال/الـ policies أو كود SQL).
 *
 * الحل: رسائل مخصصة آمنة (بتبنيها دوال قاعدة البيانات) بتعرض زي ما هي،
 * وأي خطأ تاني بيتعرض كرسالة عامة — والتفاصيل التقنية بتتحفظ في console بس.
 */

// رسائل آمنة من الدوال بتاعة الموقع — دي الوحيدة اللي بتوصل للمستخدم
const SAFE_PHRASES = [
  'محاولة واحدة',
  'غير مصرح',
  'غير مسموح',
  'يجب تسجيل الدخول',
  'لا يوجد',
  'غير موجود',
  'لم يبدأ',
  'انتهى وقت',
  'انتهى',
  'ليس لصفك',
  'غير منشور',
  'تم تسليم',
  'مصريحة',
  'الامتحان غير',
  'يجب تسجيل',
  'اختر شهر',
  'رقم ولي الأمر',
  'بيانات الدخول غير صحيحة'
];

/** هل الرسالة من رسائلنا المخصصة الآمنة (بتبدأ من دوال الـ DB)؟ */
function isSafeMessage(message) {
  if (!message) return false;
  // الرسائل الآمنة بتاعتننا كلها بالعربي أو أرقام/كلمات معروفة
  return SAFE_PHRASES.some((p) => message.includes(p));
}

/**
 * يرجّع رسالة خطأ آمنة للعرض للمستخدم.
 * @param {*} error كائن الخطأ من Supabase
 * @param {string} fallback رسالة عامة لو الخطأ مش معروف
 */
export function getFriendlyError(error, fallback) {
  const raw = error?.message || error?.error_description || '';

  // لو الرسالة من رسائلنا المخصصة → اعرضها (آمنة ولا تسرب أي شيء)
  if (isSafeMessage(raw)) {
    return raw;
  }

  // أي رسالة تانية (حتى لو فيها تفاصيل DB) → رسالة عامة بس، والتفاصيل للـ console
  if (error) {
    console.warn('[safe-error] تم حجب تفاصيل الخطأ عن المستخدم:', error);
  }
  return fallback;
}

/** يعرض رسالة خطأ لـ toast آمنة */
export function friendlyToast(toast, error, fallback) {
  toast.error(getFriendlyError(error, fallback));
}
